"""OpenUSD (UsdGeom / UsdShade / UsdPhysics) and glTF export, plus USD read-back."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import trimesh
from pxr import Gf, Kind, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade, Vt

from . import __version__
from .physics import MassProperties


@dataclass
class SurfaceMaterial:
    """Render material. Albedo comes from a texture, vertex colors, or a constant."""

    base_color: tuple[float, float, float] = (0.8, 0.8, 0.8)
    texture: Path | None = None
    use_vertex_colors: bool = False
    roughness: float = 0.5
    metallic: float = 0.0


@dataclass
class PhysicsMaterial:
    static_friction: float = 0.5
    dynamic_friction: float = 0.4
    restitution: float = 0.1


@dataclass
class AssetData:
    """Asset contents as read back from a USD file, in the root prim's frame."""

    name: str
    render_mesh: trimesh.Trimesh
    hulls: list[trimesh.Trimesh]
    mass: float | None
    center_of_mass: np.ndarray | None
    diagonal_inertia: np.ndarray | None
    principal_axes_wxyz: np.ndarray | None
    stage_info: dict = field(default_factory=dict)
    root_schemas: list[str] = field(default_factory=list)
    collider_info: list[dict] = field(default_factory=list)
    texture_paths: list[Path] = field(default_factory=list)
    has_render_material: bool = False
    physics_material: dict = field(default_factory=dict)

    def inertia_tensor(self) -> np.ndarray | None:
        if self.diagonal_inertia is None:
            return None
        from scipy.spatial.transform import Rotation

        w, x, y, z = self.principal_axes_wxyz
        r = Rotation.from_quat([x, y, z, w]).as_matrix()
        return r @ np.diag(self.diagonal_inertia) @ r.T


def _prim_name(name: str) -> str:
    clean = "".join(c if c.isalnum() or c == "_" else "_" for c in name)
    return clean if clean and not clean[0].isdigit() else f"_{clean}"


def _define_mesh(stage: Usd.Stage, path: str, mesh: trimesh.Trimesh) -> UsdGeom.Mesh:
    geom = UsdGeom.Mesh.Define(stage, path)
    pts = np.asarray(mesh.vertices, dtype=np.float32)
    geom.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(pts))
    geom.CreateFaceVertexCountsAttr(Vt.IntArray([3] * len(mesh.faces)))
    geom.CreateFaceVertexIndicesAttr(Vt.IntArray.FromNumpy(np.asarray(mesh.faces, dtype=np.int32).ravel()))
    geom.CreateExtentAttr(Vt.Vec3fArray([Gf.Vec3f(*map(float, pts.min(0))), Gf.Vec3f(*map(float, pts.max(0)))]))
    geom.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    geom.CreateOrientationAttr(UsdGeom.Tokens.rightHanded)
    geom.CreateDoubleSidedAttr(False)
    return geom


def write_usd(
    path: str | Path,
    name: str,
    mesh: trimesh.Trimesh,
    hulls: list[trimesh.Trimesh],
    mass_props: MassProperties,
    surface: SurfaceMaterial,
    physics_material: PhysicsMaterial,
    metadata: dict | None = None,
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    stage = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    UsdPhysics.SetStageKilogramsPerUnit(stage, 1.0)

    root_path = f"/{_prim_name(name)}"
    root = UsdGeom.Xform.Define(stage, root_path).GetPrim()
    stage.SetDefaultPrim(root)
    Usd.ModelAPI(root).SetKind(Kind.Tokens.component)
    root.SetAssetInfo({"name": name, "version": __version__})
    stage.GetRootLayer().documentation = f"Generated by scan2usd {__version__}"
    if metadata:
        root.SetCustomDataByKey("scan2usd:build", json.dumps(metadata, default=str))

    looks = UsdGeom.Scope.Define(stage, f"{root_path}/Looks").GetPath()
    phys_mat = define_physics_material(stage, looks.AppendChild("PM_contact"), physics_material)
    author_body(stage, root, path, mesh, hulls, mass_props, surface, looks.AppendChild("M_surface"), phys_mat)

    stage.GetRootLayer().Save()
    return path


def define_physics_material(stage: Usd.Stage, path: Sdf.Path, physics_material: PhysicsMaterial) -> UsdShade.Material:
    phys_mat = UsdShade.Material.Define(stage, path)
    pm = UsdPhysics.MaterialAPI.Apply(phys_mat.GetPrim())
    pm.CreateStaticFrictionAttr(float(physics_material.static_friction))
    pm.CreateDynamicFrictionAttr(float(physics_material.dynamic_friction))
    pm.CreateRestitutionAttr(float(physics_material.restitution))
    return phys_mat


def author_body(stage: Usd.Stage, body: Usd.Prim, usd_path: Path, mesh: trimesh.Trimesh,
                hulls: list[trimesh.Trimesh], mass_props: MassProperties, surface: SurfaceMaterial,
                material_path: Sdf.Path, phys_mat: UsdShade.Material) -> None:
    """Make `body` a rigid body with a render mesh, material, convex colliders and mass properties."""
    body_path = body.GetPath()
    UsdPhysics.RigidBodyAPI.Apply(body)
    mass_api = UsdPhysics.MassAPI.Apply(body)
    mass_api.CreateMassAttr(float(mass_props.mass))
    mass_api.CreateCenterOfMassAttr(Gf.Vec3f(*mass_props.center_of_mass))
    mass_api.CreateDiagonalInertiaAttr(Gf.Vec3f(*mass_props.principal_moments))
    w, x, y, z = mass_props.principal_axes_quat_wxyz
    mass_api.CreatePrincipalAxesAttr(Gf.Quatf(float(w), float(x), float(y), float(z)))

    mat = UsdShade.Material.Define(stage, material_path)
    pbr = UsdShade.Shader.Define(stage, mat.GetPath().AppendChild("PreviewSurface"))
    pbr.CreateIdAttr("UsdPreviewSurface")
    pbr.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(float(surface.roughness))
    pbr.CreateInput("metallic", Sdf.ValueTypeNames.Float).Set(float(surface.metallic))
    diffuse = pbr.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f)
    mat.CreateSurfaceOutput().ConnectToSource(pbr.ConnectableAPI(), "surface")

    render = _define_mesh(stage, str(body_path.AppendChild("render")), mesh)
    render.GetDoubleSidedAttr().Set(True)  # scans are often open (shoe openings, unseen bases)
    render.CreateNormalsAttr(Vt.Vec3fArray.FromNumpy(np.asarray(mesh.vertex_normals, dtype=np.float32)))
    render.SetNormalsInterpolation(UsdGeom.Tokens.vertex)
    pv_api = UsdGeom.PrimvarsAPI(render)

    if surface.texture is not None:
        uv = np.asarray(mesh.visual.uv, dtype=np.float32)
        pv_api.CreatePrimvar("st", Sdf.ValueTypeNames.TexCoord2fArray, UsdGeom.Tokens.vertex).Set(
            Vt.Vec2fArray.FromNumpy(uv)
        )
        reader = UsdShade.Shader.Define(stage, mat.GetPath().AppendChild("stReader"))
        reader.CreateIdAttr("UsdPrimvarReader_float2")
        reader.CreateInput("varname", Sdf.ValueTypeNames.Token).Set("st")
        tex = UsdShade.Shader.Define(stage, mat.GetPath().AppendChild("albedoTexture"))
        tex.CreateIdAttr("UsdUVTexture")
        rel = Path(surface.texture).resolve().relative_to(Path(usd_path).parent.resolve()).as_posix()
        tex.CreateInput("file", Sdf.ValueTypeNames.Asset).Set(Sdf.AssetPath(f"./{rel}"))
        tex.CreateInput("sourceColorSpace", Sdf.ValueTypeNames.Token).Set("sRGB")
        tex.CreateInput("wrapS", Sdf.ValueTypeNames.Token).Set("repeat")
        tex.CreateInput("wrapT", Sdf.ValueTypeNames.Token).Set("repeat")
        tex.CreateInput("st", Sdf.ValueTypeNames.Float2).ConnectToSource(reader.ConnectableAPI(), "result")
        diffuse.ConnectToSource(tex.ConnectableAPI(), "rgb")
    elif surface.use_vertex_colors:
        from .color import srgb_to_linear

        rgb = srgb_to_linear(np.asarray(mesh.visual.vertex_colors[:, :3], dtype=np.float64) / 255.0)
        render.CreateDisplayColorPrimvar(UsdGeom.Tokens.vertex).Set(Vt.Vec3fArray.FromNumpy(rgb.astype(np.float32)))
        reader = UsdShade.Shader.Define(stage, mat.GetPath().AppendChild("colorReader"))
        reader.CreateIdAttr("UsdPrimvarReader_float3")
        reader.CreateInput("varname", Sdf.ValueTypeNames.Token).Set("displayColor")
        diffuse.ConnectToSource(reader.ConnectableAPI(), "result")
    else:
        diffuse.Set(Gf.Vec3f(*surface.base_color))
        render.CreateDisplayColorPrimvar(UsdGeom.Tokens.constant).Set(Vt.Vec3fArray([Gf.Vec3f(*surface.base_color)]))
    UsdShade.MaterialBindingAPI.Apply(render.GetPrim()).Bind(mat)

    UsdGeom.Scope.Define(stage, str(body_path.AppendChild("collision")))
    for i, hull in enumerate(hulls):
        col = _define_mesh(stage, str(body_path.AppendPath(f"collision/hull_{i:03d}")), hull)
        col.CreatePurposeAttr(UsdGeom.Tokens.guide)
        prim = col.GetPrim()
        UsdPhysics.CollisionAPI.Apply(prim)
        UsdPhysics.MeshCollisionAPI.Apply(prim).CreateApproximationAttr(UsdPhysics.Tokens.convexHull)
        UsdShade.MaterialBindingAPI.Apply(prim).Bind(phys_mat, UsdShade.Tokens.weakerThanDescendants, "physics")


def _mesh_from_prim(prim: Usd.Prim, root: Usd.Prim, cache: UsdGeom.XformCache) -> trimesh.Trimesh:
    geom = UsdGeom.Mesh(prim)
    pts = np.asarray(geom.GetPointsAttr().Get(), dtype=np.float64)
    counts = np.asarray(geom.GetFaceVertexCountsAttr().Get(), dtype=np.int64)
    idx = np.asarray(geom.GetFaceVertexIndicesAttr().Get(), dtype=np.int64)
    if not np.all(counts == 3):
        raise ValueError(f"{prim.GetPath()} has non-triangle faces")
    xf, _ = cache.ComputeRelativeTransform(prim, root)
    m = np.asarray(xf, dtype=np.float64)
    pts = np.c_[pts, np.ones(len(pts))] @ m
    tm = trimesh.Trimesh(pts[:, :3], idx.reshape(-1, 3), process=False)
    pv = UsdGeom.PrimvarsAPI(prim).GetPrimvar("displayColor")
    if pv and pv.HasValue():
        lin = np.asarray(pv.Get(), dtype=np.float64)
        if pv.GetInterpolation() == UsdGeom.Tokens.constant or len(lin) == 1:
            lin = np.tile(lin[:1], (len(tm.vertices), 1))
        if len(lin) == len(tm.vertices):
            from .color import linear_to_srgb

            rgb8 = np.round(linear_to_srgb(lin) * 255).astype(np.uint8)
            tm.visual = trimesh.visual.ColorVisuals(tm, vertex_colors=np.c_[rgb8, np.full(len(rgb8), 255, np.uint8)])
    st = UsdGeom.PrimvarsAPI(prim).GetPrimvar("st")
    if st and st.HasValue() and st.GetInterpolation() == UsdGeom.Tokens.vertex:
        uv = np.asarray(st.Get(), dtype=np.float64)
        if len(uv) == len(tm.vertices):
            tm._scan2usd_st = uv  # attached as a texture once the image path is known
    return tm


def read_usd(path: str | Path) -> AssetData:
    path = Path(path)
    stage = Usd.Stage.Open(str(path))
    if stage is None:
        raise ValueError(f"cannot open {path}")
    root = stage.GetDefaultPrim()
    if not root:
        raise ValueError(f"{path} has no defaultPrim")
    cache = UsdGeom.XformCache()

    render_meshes, hulls, collider_info = [], [], []
    textures: list[Path] = []
    has_material = False
    phys_mat: dict = {}
    for prim in Usd.PrimRange(root):
        if prim.IsA(UsdGeom.Mesh):
            is_collider = prim.HasAPI(UsdPhysics.CollisionAPI)
            tm = _mesh_from_prim(prim, root, cache)
            if is_collider:
                approx = UsdPhysics.MeshCollisionAPI(prim).GetApproximationAttr().Get()
                hulls.append(tm)
                collider_info.append({"path": str(prim.GetPath()), "approximation": str(approx)})
                if not phys_mat:
                    bound, _ = UsdShade.MaterialBindingAPI(prim).ComputeBoundMaterial("physics")
                    if bound and bound.GetPrim().HasAPI(UsdPhysics.MaterialAPI):
                        api = UsdPhysics.MaterialAPI(bound.GetPrim())
                        phys_mat = {
                            "static_friction": api.GetStaticFrictionAttr().Get(),
                            "dynamic_friction": api.GetDynamicFrictionAttr().Get(),
                            "restitution": api.GetRestitutionAttr().Get(),
                        }
            elif UsdGeom.Imageable(prim).ComputePurpose() in (UsdGeom.Tokens.default_, UsdGeom.Tokens.render):
                render_meshes.append(tm)
                bound, _ = UsdShade.MaterialBindingAPI(prim).ComputeBoundMaterial()
                if bound:
                    has_material = True
        elif prim.IsA(UsdShade.Shader):
            shader = UsdShade.Shader(prim)
            if shader.GetIdAttr().Get() == "UsdUVTexture":
                f = shader.GetInput("file")
                if f and f.Get() is not None:
                    asset = f.Get()
                    resolved = asset.resolvedPath or str((path.parent / asset.path).resolve())
                    textures.append(Path(resolved))

    if not render_meshes:
        raise ValueError(f"{path} contains no render mesh")
    render = trimesh.util.concatenate(render_meshes) if len(render_meshes) > 1 else render_meshes[0]
    if len(render_meshes) == 1 and textures and textures[0].exists() and hasattr(render, "_scan2usd_st"):
        from PIL import Image

        render.visual = trimesh.visual.TextureVisuals(uv=render._scan2usd_st, image=Image.open(textures[0]))

    mass = com = diag = axes = None
    if root.HasAPI(UsdPhysics.MassAPI):
        api = UsdPhysics.MassAPI(root)
        mass = api.GetMassAttr().Get()
        c = api.GetCenterOfMassAttr().Get()
        d = api.GetDiagonalInertiaAttr().Get()
        q = api.GetPrincipalAxesAttr().Get()
        com = np.array(c, dtype=np.float64) if c is not None else None
        diag = np.array(d, dtype=np.float64) if d is not None else None
        if q is not None:
            axes = np.array([q.GetReal(), *q.GetImaginary()], dtype=np.float64)

    return AssetData(
        name=root.GetName(),
        render_mesh=render,
        hulls=hulls,
        mass=mass,
        center_of_mass=com,
        diagonal_inertia=diag,
        principal_axes_wxyz=axes,
        stage_info={
            "up_axis": str(UsdGeom.GetStageUpAxis(stage)),
            "meters_per_unit": UsdGeom.GetStageMetersPerUnit(stage),
            "kilograms_per_unit": UsdPhysics.GetStageKilogramsPerUnit(stage),
            "default_prim": root.GetName(),
        },
        root_schemas=list(root.GetAppliedSchemas()),
        collider_info=collider_info,
        texture_paths=textures,
        has_render_material=has_material,
        physics_material=phys_mat,
    )


def export_gltf(path: str | Path, mesh: trimesh.Trimesh) -> Path:
    """Write a binary glTF of the render mesh, converted to glTF's Y-up convention."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    out = mesh.copy()
    out.apply_transform(trimesh.transformations.rotation_matrix(-np.pi / 2.0, [1, 0, 0]))
    out.export(str(path))
    return path
